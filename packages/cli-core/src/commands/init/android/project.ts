export const GENERATED = "Generated by Clerk CLI";
export const KEY_RESOURCE = "clerk_publishable_key";
export const GENERATED_APPLICATION = "ClerkApplication";

export interface InspectOptions {
  root: string;
  module?: string;
  /** The final applicationId, when Gradle's isn't one plain literal or a variant changes it. */
  applicationId?: string;
  sdk: AndroidSdk;
  minimumVersion: string;
  signal?: AbortSignal;
  chooseModule?: ChooseModule;
}

export interface Selection {
  root: string;
  module: string;
  /** The Gradle project path (`:app`), from settings.gradle when it names the module. */
  gradlePath: string;
  namespace: string;
  applicationId: string;
  applicationIdSource: "gradle" | "gradle-debug" | "explicit";
}

export interface ApplicationClass {
  /** Fully qualified. */
  className: string;
  /** Whether the manifest's `<application>` names it. */
  registered: boolean;
  /** Where its Kotlin source is, or would be created. */
  path: string;
  source?: FileSnapshot;
  /** Whether `Clerk.initialize` is called: by this setup's recipe, by the project's own code, or not. */
  initialized: "managed" | "custom" | "none";
  /** Whether setup can add the initialization after `super.onCreate()`. */
  editable: boolean;
  /** Why it can't be edited, when it can't. */
  reason?: string;
}

export interface Inspection {
  selection: Selection;
  sdk: AndroidSdk;
  minimumVersion: string;
  build: FileSnapshot;
  catalog?: FileSnapshot;
  parsedCatalog?: Catalog;
  rootBuild?: FileSnapshot;
  manifest: FileSnapshot;
  internetPermission: boolean;
  application: ApplicationClass;
  keyResource: {
    path: string;
    snapshot?: FileSnapshot;
    /** Whether the file is one this setup wrote, so it can be rewritten. */
    managed: boolean;
    key?: string;
  };
  minSdk: {
    value?: number;
    source: "literal" | "catalog" | "unknown";
    /** Offsets in the build script of a literal value, when it can be rewritten. */
    edit?: { start: number; end: number };
    /** The `[versions]` key a catalog reference reads, when it can be raised there. */
    catalogKey?: string;
  };
  /** `applied` is unknown when convention plugins or composite builds may supply Kotlin. */
  kotlin: { version?: string; source: string; applied: "yes" | "no" | "unknown" };
  agp: { version?: string };
  dependencies: ClerkDependency[];
}

async function optionalSnapshot(root: string, path: string): Promise<FileSnapshot | undefined> {
  if (!(await Bun.file(join(root, path)).exists())) return undefined;
  return snapshotFile(root, path);
}

/** The applicationId the installed debug build carries, from `defaultConfig` and a debug suffix. */
function discoverApplicationId(
  build: string,
  android: { open: number; close: number },
  defaultConfig: { open: number; close: number },
): { applicationId?: string; source: Selection["applicationIdSource"]; reason?: string } {
  const masked = maskCode(build);
  const base = literal(build.slice(defaultConfig.open, defaultConfig.close), "applicationId");
  if (!base || !PACKAGE_NAME.test(base))
    return {
      source: "gradle",
      reason:
        "defaultConfig doesn't set applicationId to one plain literal, and the Gradle namespace is not the installed applicationId.",
    };
  if ([...masked.matchAll(/\bapplicationId\b/g)].length !== 1)
    return { source: "gradle", reason: "applicationId is set in more than one place." };
  if (/\b(?:productFlavors|androidComponents|applicationVariants)\b/.test(masked))
    return {
      source: "gradle",
      reason: "the build declares product flavors or variant-specific build logic.",
    };
  const suffixes = [...masked.matchAll(/\bapplicationIdSuffix\b/g)];
  if (!suffixes.length) return { applicationId: base, source: "gradle" };
  // Setup targets the development instance, which the debug variant uses, so the debug build
  // type's suffix is the one that counts. Any other suffix needs the final value spelled out.
  const buildTypes = childBlock(build, android, "buildTypes");
  const debug = buildTypes && childBlock(build, buildTypes, "debug");
  const inDebug = debug
    ? suffixes.filter((match) => match.index > debug.open && match.index < debug.close)
    : [];
  if (!debug || inDebug.length !== suffixes.length || suffixes.length !== 1)
    return {
      source: "gradle",
      reason: "applicationIdSuffix is set outside the debug build type.",
    };
  const suffix = literal(build.slice(debug.open, debug.close), "applicationIdSuffix");
  if (!suffix || !/^(?:\.[A-Za-z][A-Za-z0-9_]*)+$/.test(suffix))
    return { source: "gradle", reason: "the debug applicationIdSuffix isn't a plain literal." };
  return { applicationId: base + suffix, source: "gradle-debug" };
}

function discoverMinSdk(
  build: string,
  defaultConfig: { open: number; close: number },
  catalog?: Catalog,
): Inspection["minSdk"] {
  const section = maskCode(build.slice(defaultConfig.open, defaultConfig.close));
  const matches = [
    ...section.matchAll(
      /\bminSdk(?:Version)?\s*(?:=\s*)?(\d+|libs\.versions\.([\w.]+)\.get\(\)\.toInt\(\))/g,
    ),
  ];
  if (matches.length !== 1) return { source: "unknown" };
  const match = matches[0]!;
  const start = defaultConfig.open + match.index + match[0].length - match[1]!.length;
  const edit = { start, end: start + match[1]!.length };
  if (match[2]) {
    const catalogKey = Object.keys(catalog?.versions ?? {}).find(
      (key) => key.replace(/[-_]/g, ".") === match[2],
    );
    const value = catalogKey ? catalog!.versions[catalogKey] : undefined;
    return value && /^\d+$/.test(value)
      ? { value: Number(value), source: "catalog", catalogKey }
      : { source: "unknown" };
  }
  return { value: Number(match[1]), source: "literal", edit };
}

/** The Kotlin Gradle plugin AGP 9.0 through 9.4 depend on, used by built-in Kotlin when none is declared. */
const AGP_BUNDLED_KOTLIN = "2.2.10";
const KOTLIN_PLUGIN_VERSION =
  /(?:id\s*\(\s*["']org\.jetbrains\.kotlin\.[\w.]+["']\s*\)|kotlin\s*\(\s*["'][\w.]+["']\s*\))\s+version\s+["'](\d+\.\d+(?:\.\d+)?)["']/g;
const AGP_PLUGIN_VERSION =
  /id\s*\(\s*["']com\.android\.application["']\s*\)\s+version\s+["'](\d+\.\d+(?:\.\d+)?)["']/g;

/** Plugin ids whose effect on the Kotlin toolchain is known; anything else may be a convention plugin. */
const RECOGNIZED_PLUGIN =
  /^(?:com\.android\.|org\.jetbrains\.kotlin|org\.jetbrains\.compose|com\.google\.|androidx\.|kotlin-)/;

function discoverToolchain(
  sources: { path: string; source: string }[],
  catalog: Catalog | undefined,
  moduleBuild: string,
  /** The build has buildSrc, build-logic, or an included build: convention plugins may apply Kotlin. */
  conventionPlugins: boolean,
): { kotlin: Inspection["kotlin"]; agp: Inspection["agp"] } {
  let agp: string | undefined;
  let kotlin: { version?: string; source: string } | undefined;
  for (const { path, source } of sources) {
    const visible = maskCode(source, false);
    for (const match of visible.matchAll(AGP_PLUGIN_VERSION)) agp ??= match[1];
    for (const match of visible.matchAll(KOTLIN_PLUGIN_VERSION))
      kotlin ??= { version: match[1], source: `plugin version in ${path}` };
    const classpath = /org\.jetbrains\.kotlin:kotlin-gradle-plugin:(\d+\.\d+(?:\.\d+)?)/.exec(
      visible,
    );
    if (classpath) kotlin ??= { version: classpath[1], source: `classpath in ${path}` };
    const agpClasspath = /com\.android\.tools\.build:gradle:(\d+\.\d+(?:\.\d+)?)/.exec(visible);
    if (agpClasspath) agp ??= agpClasspath[1];
  }
  if (catalog)
    for (const [alias, plugin] of Object.entries(catalog.plugins)) {
      const used = sources.some(({ source }) =>
        usesAccessor(source, catalogAccessor(alias, "plugins")),
      );
      if (!used) continue;
      if (plugin.id === "com.android.application") agp ??= catalogVersion(catalog, plugin);
      // Any Kotlin plugin (android, compose, serialization) puts that Kotlin Gradle plugin on
      // the classpath, which is the compiler AGP's built-in Kotlin uses too.
      if (plugin.id?.startsWith("org.jetbrains.kotlin"))
        kotlin ??= {
          version: catalogVersion(catalog, plugin),
          source: "gradle/libs.versions.toml",
        };
    }
  const module = maskCode(moduleBuild, false);
  const appliesKotlinPlugin =
    /["']org\.jetbrains\.kotlin\.android["']|kotlin\s*\(\s*["']android["']\s*\)|["']kotlin-android["']/.test(
      module,
    ) ||
    Object.entries(catalog?.plugins ?? {}).some(
      ([alias, plugin]) =>
        plugin.id === "org.jetbrains.kotlin.android" &&
        usesAccessor(moduleBuild, catalogAccessor(alias, "plugins")),
    );
  const builtIn = agp !== undefined && (semver.coerce(agp)?.major ?? 0) >= 9;
  const aliased = aliasedPluginIds(moduleBuild, catalog);
  const unrecognized =
    conventionPlugins ||
    aliased.unresolved > 0 ||
    [...literalPluginIds(moduleBuild), ...aliased.known].some((id) => !RECOGNIZED_PLUGIN.test(id));
  // Without a Kotlin Gradle plugin on the classpath, AGP 9's built-in Kotlin compiles with the
  // version AGP itself depends on: 2.2.10 for every 9.x release so far. A convention plugin can
  // put another on the classpath, so then the version stays unknown rather than assumed.
  if (!kotlin && builtIn && !unrecognized)
    kotlin = { version: AGP_BUNDLED_KOTLIN, source: `AGP ${agp}'s built-in Kotlin` };
  return {
    kotlin: {
      version: kotlin?.version,
      source:
        kotlin?.source ??
        (unrecognized
          ? "not declared where clerk init reads it; a convention plugin or included build may set it"
          : "not declared"),
      applied: appliesKotlinPlugin || builtIn ? "yes" : unrecognized ? "unknown" : "no",
    },
    agp: { version: agp },
  };
}

/** Comments blanked, offsets kept. */
export function maskXml(source: string): string {
  return source.replace(/<!--[\s\S]*?-->/g, (comment) => " ".repeat(comment.length));
}

async function inspectApplicationClass(
  root: string,
  module: string,
  namespace: string,
  manifestApplication: string,
): Promise<ApplicationClass> {
  const nameMatch = /\sandroid:name\s*=\s*["']([^"']*)["']/.exec(manifestApplication);
  const name = nameMatch?.[1];
  if (name !== undefined && !/^\.?[A-Za-z_][\w.]*$/.test(name))
    throw unsupported("The manifest's application android:name isn't a plain class name.");
  const className = name
    ? name.startsWith(".")
      ? namespace + name
      : name.includes(".")
        ? name
        : `${namespace}.${name}`
    : `${namespace}.${GENERATED_APPLICATION}`;
  const relativeSource = className.replaceAll(".", "/");
  const candidates = [
    modulePath(module, join("src/main/kotlin", `${relativeSource}.kt`)),
    modulePath(module, join("src/main/java", `${relativeSource}.kt`)),
  ];
  const found: FileSnapshot[] = [];
  for (const path of candidates)
    if (await Bun.file(join(root, path)).exists()) found.push(await snapshotFile(root, path));
  if (found.length > 1)
    throw unsupported(
      `${className} has Kotlin sources under both src/main/kotlin and src/main/java.`,
    );
  const javaPath = modulePath(module, join("src/main/java", `${relativeSource}.java`));
  const java = await Bun.file(join(root, javaPath)).exists();
  const source = found[0];
  const path = source?.path ?? (java ? javaPath : candidates[1]!);
  const result: ApplicationClass = {
    className,
    registered: name !== undefined,
    path,
    source,
    initialized: "none",
    editable: false,
  };
  if (!source) {
    if (java) {
      result.reason = `${className} is a Java class; initialize Clerk in its onCreate manually.`;
      return result;
    }
    if (name !== undefined) {
      result.reason = `Kotlin source for ${className} was not found under src/main/kotlin or src/main/java; initialize Clerk in it manually.`;
      return result;
    }
    // Nothing registered and nothing on disk: setup generates the class.
    result.editable = true;
    return result;
  }
  const masked = maskCode(source.source);
  if (/\bClerk\.initialize\s*\(/.test(masked)) {
    result.initialized = /R\.string\.clerk_publishable_key\b/.test(masked) ? "managed" : "custom";
    return result;
  }
  if (name === undefined) {
    // An unregistered class with the generated name: only our own file can be adopted.
    if (!source.source.includes(GENERATED))
      throw unsupported(
        `${path} exists but the manifest doesn't register it; register it with android:name, or remove it, then rerun clerk init.`,
      );
  }
  const onCreate = [...masked.matchAll(/\boverride\s+fun\s+onCreate\s*\(\s*\)/g)];
  const supers = [...masked.matchAll(/\bsuper\.onCreate\s*\(\s*\)/g)];
  if (onCreate.length !== 1 || supers.length !== 1 || supers[0]!.index < onCreate[0]!.index) {
    result.reason = `${className} needs one onCreate override that calls super.onCreate(); initialize Clerk in it manually.`;
    return result;
  }
  const end = supers[0]!.index + supers[0]![0].length;
  if (!/^[ \t]*(?:$|[\r\n;}])/.test(masked.slice(end))) {
    result.reason = `${className} calls super.onCreate() inside a larger expression; initialize Clerk in it manually.`;
    return result;
  }
  result.editable = true;
  return result;
}

/**
 * Reads everything setup needs from the selected module. Unsupported layouts are refused with the
 * reason, never guessed at. Nothing is written.
 */
export async function inspectAndroidProject(options: InspectOptions): Promise<Inspection> {
  const root = options.root;
  options.signal?.throwIfAborted();
  if (options.applicationId !== undefined && !PACKAGE_NAME.test(options.applicationId))
    throw setupError(
      "--android-package must be the installed app's applicationId, such as com.example.app or com.example.app.debug.",
    );
  const catalog = await optionalSnapshot(root, "gradle/libs.versions.toml");
  const parsedCatalog = catalog ? parseCatalog(catalog.source) : undefined;
  const { module, build } = await selectModule(
    root,
    parsedCatalog,
    options.module,
    options.chooseModule,
  );
  const source = build.source;
  const android = topLevelBlocks(source, "android");
  if (android.length !== 1) throw unsupported(`${build.path} needs exactly one android block.`);
  const defaultConfig = childBlock(source, android[0]!, "defaultConfig");
  if (!defaultConfig) throw unsupported(`${build.path} needs one android.defaultConfig block.`);
  const namespace = literal(source.slice(android[0]!.open, android[0]!.close), "namespace");
  if (!namespace || !PACKAGE_NAME.test(namespace))
    throw unsupported(`${build.path} must set android.namespace to one plain package name.`);
  const discovered = discoverApplicationId(source, android[0]!, defaultConfig);
  const applicationId = options.applicationId ?? discovered.applicationId;
  if (!applicationId)
    throw unsupported(
      `The installed applicationId can't be read from ${build.path}: ${discovered.reason} Pass --android-package with the final applicationId of the build you install.`,
    );
  const rootBuild =
    module === "."
      ? undefined
      : ((await optionalSnapshot(root, "build.gradle.kts")) ??
        (await optionalSnapshot(root, "build.gradle")));
  // Plugin versions can live in settings' pluginManagement; includes name the Gradle project path.
  const settingsScript =
    (await optionalSnapshot(root, "settings.gradle.kts")) ??
    (await optionalSnapshot(root, "settings.gradle"));
  const settings = settingsScript ? parseSettings(settingsScript.source) : undefined;
  const conventionPlugins =
    settings?.includesBuilds === true ||
    (await Bun.file(join(root, "buildSrc", "build.gradle.kts")).exists()) ||
    (await Bun.file(join(root, "buildSrc", "build.gradle")).exists()) ||
    (await Bun.file(join(root, "build-logic", "settings.gradle.kts")).exists()) ||
    (await Bun.file(join(root, "build-logic", "settings.gradle")).exists());
  const toolchain = discoverToolchain(
    [build, ...(rootBuild ? [rootBuild] : []), ...(settingsScript ? [settingsScript] : [])].map(
      (item) => ({ path: item.path, source: item.source }),
    ),
    parsedCatalog,
    source,
    conventionPlugins,
  );
  const gradlePath =
    [...(settings?.projects ?? [])].find(
      ([, dir]) => dir === (module === "." ? "" : module),
    )?.[0] ?? (module === "." ? ":" : `:${module.split("/").join(":")}`);
  const manifest = await snapshotFile(root, modulePath(module, "src/main/AndroidManifest.xml"));
  if (/<!DOCTYPE|<!ENTITY/i.test(manifest.source))
    throw unsupported("AndroidManifest.xml declares a DOCTYPE or entities.");
  const xml = maskXml(manifest.source);
  if (!/xmlns:android\s*=\s*["']http:\/\/schemas\.android\.com\/apk\/res\/android["']/.test(xml))
    throw unsupported("AndroidManifest.xml must declare the android XML namespace.");
  const applications = [...xml.matchAll(/<application\b[^>]*>/g)];
  if (applications.length !== 1)
    throw unsupported("AndroidManifest.xml needs exactly one application element.");
  const internetPermission =
    /<uses-permission\b[^>]*android:name\s*=\s*["']android\.permission\.INTERNET["']/.test(xml);
  const application = await inspectApplicationClass(root, module, namespace, applications[0]![0]);
  const keyResourcePath = modulePath(module, "src/main/res/values/clerk.xml");
  const keyResource = await optionalSnapshot(root, keyResourcePath);
  const keyMatch = keyResource
    ? /<string name="clerk_publishable_key" translatable="false">(pk_test_[A-Za-z0-9+/=_-]+)<\/string>/.exec(
        keyResource.source,
      )
    : null;
  const managed =
    !!keyResource &&
    keyResource.source.includes(`<!-- ${GENERATED} -->`) &&
    (keyResource.source.match(/<string\b/g) ?? []).length === 1 &&
    keyMatch !== null;
  if (keyResource && !managed)
    throw unsupported(`${keyResourcePath} exists and wasn't written by clerk init.`);
  for await (const path of new Bun.Glob(`${modulePath(module, "src")}/**/res/values*/*.xml`).scan({
    cwd: root,
    onlyFiles: true,
    followSymlinks: false,
  })) {
    if (path === keyResourcePath) continue;
    const text = await Bun.file(join(root, path)).text();
    if (new RegExp(`name\\s*=\\s*["']${KEY_RESOURCE}["']`).test(text))
      throw unsupported(
        `${path} already defines a ${KEY_RESOURCE} resource; keep it and initialize Clerk manually.`,
      );
  }
  options.signal?.throwIfAborted();
  return {
    selection: {
      root,
      module,
      gradlePath,
      namespace,
      applicationId,
      applicationIdSource: options.applicationId !== undefined ? "explicit" : discovered.source,
    },
    sdk: options.sdk,
    minimumVersion: options.minimumVersion,
    build,
    catalog,
    parsedCatalog,
    rootBuild,
    manifest,
    internetPermission,
    application,
    keyResource: {
      path: keyResourcePath,
      snapshot: keyResource,
      managed,
      key: keyMatch?.[1],
    },
    minSdk: discoverMinSdk(source, defaultConfig, parsedCatalog),
    kotlin: toolchain.kotlin,
    agp: toolchain.agp,
    dependencies: findClerkDependencies(source, parsedCatalog),
  };
}
